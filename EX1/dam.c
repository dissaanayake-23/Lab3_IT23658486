#include<stdio.h>
int main(void){
	const double gravity = 9.80;
	const double efficiency = 0.9;
	const double water_density = 1000.0;
	double height, flow, mass, work, power_MW;

	printf("Enter the height of the dam:");
	scanf("%lf", &height);
	printf("Enter the water flow:");
	scanf("%lf", &flow);
	mass = flow * water_density;
	work = mass * gravity *height;
	power_MW = efficiency * work / 1000000.0;

	printf("Predicted power generated by the hydroelectric dam: %.2f megawatts\n", power_MW);
	return 0;
}
